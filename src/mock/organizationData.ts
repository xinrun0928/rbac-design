/** 将扁平数据转为树结构 */
export function buildOrgTree(data: Organization[]): OrgTreeNode[] {
  const map = new Map<number, OrgTreeNode>()
  const roots: OrgTreeNode[] = []

  // 先创建所有节点
  data.forEach(item => {
    map.set(item.orgId, {
      orgId: item.orgId,
      orgName: item.orgName,
      orgCode: item.orgCode,
      parentId: item.parentId,
      packageTypes: item.packageTypes || [],
      children: []
    })
  })

  // 再构建树
  data.forEach(item => {
    const node = map.get(item.orgId)!
    if (item.parentId === 0 || !map.has(item.parentId)) {
      roots.push(node)
    } else {
      const parent = map.get(item.parentId)!
      if (!parent.children) parent.children = []
      parent.children.push(node)
    }
  })

  return roots
}
